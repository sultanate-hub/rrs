import { chromium } from "playwright-core";
import { USERS, signIn } from "./creds.mjs";
const CHROME = "C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe";
const OUT = "C:\\Users\\ASUGIR\\Desktop\\Bumsa\\rrs-asv\\screenshots";
const browser = await chromium.launch({ executablePath: CHROME, headless: true });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await signIn(page, USERS.ipo1);
await page.locator(".nav-item", { hasText: "Cases" }).click();
await page.waitForSelector(".table-cases");
await page.locator(".table-cases tbody tr").last().click();
await page.waitForSelector(".case-head");
await page.locator(".tab", { hasText: "Arrests" }).click();
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}\\20-arrests.png` });
await page.getByRole("button", { name: /Record arrest/i }).click();
await page.waitForSelector("#arrest-form");
await page.locator("#arrest-form input").nth(2).fill("Assault");
await page.getByRole("button", { name: /Record arrest/i }).last().click();
await page.waitForTimeout(400);
console.log("ERRORS", errors.length ? errors : "none");
await browser.close();
